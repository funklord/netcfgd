/*
 * parse_test.c -- the grammar, the recovery, and the bound on the stack.
 *
 * WHY THIS EXISTS
 *   The parser is the thing that reads a file a person edited on a machine
 *   with no network, so two properties matter more than the shapes it
 *   accepts: it must say something useful about every mistake rather than the
 *   first, and it must not fall over on a file that is not a configuration at
 *   all. A daemon that re-reads its configuration directory whenever anything
 *   in it changes turns "the parser crashed" into "the machine has no
 *   network", and `cargo fuzz` reached that crash twice before the limit
 *   below existed.
 *
 *   So the cases here are not a sweep of the grammar. Each is a rule the
 *   language has -- a block that may be labelled or not, a list that may span
 *   lines, a statement that ends at a newline or a semicolon or a `}` -- or a
 *   defect that was found: the run of `{` that exhausted the stack, kept
 *   verbatim, and the run of `[` that did it again down a path the first fix
 *   could not see.
 */
#include "ncfg/ast.h"
#include "ncfg/base.h"
#include "ncfg/parse.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int failures;

static void check(int condition, const char *what)
{
	printf("%-58s %s\n", what, condition ? "ok" : "FAILED");
	if (!condition) {
		failures++;
	}
}

